export default function LifeGenerator({
  language,
  onBack,
}: Props) {
  const data = DATA[language];

  const langCode = language === "TH" ? "th" : "en";

  const [result, setResult] =
    useState<ResultIndices | null>(null);

  const [loading, setLoading] =
    useState(false);

  const [done, setDone] =
    useState(false);

  const [displayJob, setDisplayJob] =
    useState("—");

  const [displayMoney, setDisplayMoney] =
    useState("—");

  const [displayLove, setDisplayLove] =
    useState("—");

  useEffect(() => {
    if (!result) {
      setDisplayJob("—");
      setDisplayMoney("—");
      setDisplayLove("—");
      return;
    }

    setDisplayJob(data.jobs[result.job]);
    setDisplayMoney(data.money[result.money]);
    setDisplayLove(data.love[result.love]);
  }, [language, result, data.jobs, data.money, data.love]);

  const randomIndex = (length: number) => {
    return Math.floor(Math.random() * length);
  };

  const generateLife = () => {
    if (loading) return;

    setLoading(true);
    setDone(false);
    setResult(null);

    setDisplayJob("...");
    setDisplayMoney("...");
    setDisplayLove("...");

    const jobIndex = randomIndex(DATA.EN.jobs.length);
    const moneyIndex = randomIndex(DATA.EN.money.length);
    const loveIndex = randomIndex(DATA.EN.love.length);
    const endingIndex = randomIndex(DATA.EN.endings.length);

    setTimeout(() => {
      setDisplayJob(data.jobs[jobIndex]);
    }, 450);

    setTimeout(() => {
      setDisplayMoney(data.money[moneyIndex]);
    }, 900);

    setTimeout(() => {
      setDisplayLove(data.love[loveIndex]);
    }, 1350);

    setTimeout(() => {
      setResult({
        job: jobIndex,
        money: moneyIndex,
        love: loveIndex,
        ending: endingIndex,
      });

      setDone(true);
      setLoading(false);
    }, 1750);
  };

  return (
    <motion.div
      initial={{ opacity: 0 }}
      animate={{ opacity: 1 }}
      lang={langCode}
      className="flex h-full min-h-0 w-full max-w-full min-w-0 flex-col overflow-hidden"
    >
      {/* BACK */}

      <button
        onClick={onBack}
        className="
          flex
          w-fit
          max-w-full
          shrink-0
          items-center
          gap-2
          text-sm
          font-medium
          text-black/70
          transition-colors
          hover:text-black
        "
      >
        <span className="text-lg">←</span>

        {language === "EN"
          ? "Back to Mini Games"
          : "กลับไปหน้า Mini Games"}
      </button>

      {/* HEADER */}

      <div className="mt-4 min-w-0 shrink-0 sm:mt-7">
        <div className="mini-micro mb-2 sm:mb-3">
          {data.eyebrow}
        </div>

        <h1
          className="
            mini-page-title
            text-3xl
            leading-tight
            sm:text-6xl
          "
        >
          {data.title}
        </h1>

        <p
          className="
            mini-readable
            mt-1
            max-w-2xl
            break-words
            break-words
            text-sm
            leading-5
            sm:text-base
          "
        >
          {data.subtitle}
        </p>
      </div>

      {/* GAME */}

      <div
        className="
          life-generator
          mt-3
          min-h-0
          w-full
          max-w-full
          min-w-0
          flex-1
          overflow-hidden
          border
          p-2.5
          sm:mt-5
          sm:p-5
        "
      >
        <div className="mini-corners" />

        {/* SLOTS */}

        <div
          className="
            grid
            min-h-0
            gap-1.5
            sm:grid-cols-3
            sm:gap-3
          "
          style={{
            height: done
              ? "48%"
              : "56%",
          }}
        >
          <LifeSlot
            number="01"
            label={data.labels.job}
            value={displayJob}
            active={loading}
            lang={langCode}
          />

          <LifeSlot
            number="02"
            label={data.labels.money}
            value={displayMoney}
            active={loading}
            lang={langCode}
          />

          <LifeSlot
            number="03"
            label={data.labels.love}
            value={displayLove}
            active={loading}
            lang={langCode}
          />
        </div>

        {/* STATUS */}

        <div
          className="
            mt-2
            flex
            min-w-0
            items-center
            justify-between
            gap-2
            border-t
            border-black/10
            pt-2
            sm:mt-3
            sm:pt-3
          "
        >
          <span className="mini-micro min-w-0 truncate">
            {loading
              ? data.building
              : done
                ? data.final
                : data.ready}
          </span>

          <span className="mini-micro shrink-0">
            {loading
              ? data.running
              : data.idle}
          </span>
        </div>

        {/* BUTTON */}

        <button
          onClick={generateLife}
          disabled={loading}
          className="
            mini-primary-button
            mt-2
            flex
            w-full
            max-w-full
            min-w-0
            items-center
            justify-center
            gap-3
            overflow-hidden
            py-3
            text-sm
            font-medium
            sm:py-4
          "
        >
          <span className="relative z-10 truncate">
            {loading
              ? data.building
              : done
                ? data.again
                : data.button}
          </span>

          {!loading && (
            <span className="relative z-10 text-lg">
              →
            </span>
          )}
        </button>

        {/* RESULT */}

        {done && result && (
          <motion.div
            initial={{
              opacity: 0,
              y: 10,
            }}
            animate={{
              opacity: 1,
              y: 0,
            }}
            className="
              mini-result
              mt-3
              border
              p-3
              sm:p-4
            "
          >
            <div className="mini-micro mb-1.5">
              {data.resultTitle}
            </div>

            <p
              className="
                break-words
                text-sm
                font-medium
                leading-6
                text-black
                sm:text-base
              "
            >
              “{data.endings[result.ending]}”
            </p>
          </motion.div>
        )}
      </div>

      {/* DISCLAIMER */}

      <div
        className="
          mt-1
          min-w-0
          shrink-0
          overflow-hidden
          text-right
          text-[10px]
          leading-5
          text-black/35
        "
      >
        <span className="block truncate">
          {data.disclaimer}
        </span>
      </div>
    </motion.div>
  );
}

